from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from config.config import REPORTS_DIR


def safe_text(value: Any, default: str = 'N/A') -> str:
    if value is None or str(value).strip() == '':
        return default
    if isinstance(value, (list, tuple)):
        clean_items = [str(item).strip() for item in value if item is not None and str(item).strip()]
        return ', '.join(clean_items) if clean_items else default
    return str(value).strip()


def parse_top_predictions(raw: Any) -> list[dict[str, Any]]:
    if isinstance(raw, list):
        return raw
    if isinstance(raw, str):
        try:
            parsed = json.loads(raw)
            if isinstance(parsed, list):
                return parsed
        except Exception:
            return []
    return []


def generate_pdf_report(disease_data: dict[str, Any], output_path: str | Path | None = None) -> str:
    report_dir = Path(REPORTS_DIR)
    report_dir.mkdir(parents=True, exist_ok=True)

    timestamp_str = datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')
    file_name = f"analysis_report_{timestamp_str}.pdf"
    final_path = Path(output_path) if output_path else report_dir / file_name
    final_path.parent.mkdir(parents=True, exist_ok=True)

    doc = SimpleDocTemplate(
        str(final_path),
        pagesize=letter,
        leftMargin=0.5 * inch,
        rightMargin=0.5 * inch,
        topMargin=0.5 * inch,
        bottomMargin=0.5 * inch,
    )
    story = []
    styles = getSampleStyleSheet()

    # Color definitions
    primary_green = colors.HexColor('#1b5e20')
    secondary_green = colors.HexColor('#2e7d32')
    light_bg = colors.HexColor('#f1f8e9')
    table_header_bg = colors.HexColor('#c8e6c9')
    border_color = colors.HexColor('#81c784')
    alert_color = colors.HexColor('#e65100')
    charcoal = colors.HexColor('#212121')

    # Typography styles
    title_style = ParagraphStyle(
        'MainTitle',
        parent=styles['Title'],
        fontName='Helvetica-Bold',
        fontSize=18,
        leading=22,
        textColor=primary_green,
        alignment=0,
    )
    subtitle_style = ParagraphStyle(
        'Subtitle',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=10,
        leading=14,
        textColor=colors.dimgrey,
    )
    section_style = ParagraphStyle(
        'SectionHeader',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=secondary_green,
        spaceBefore=10,
        spaceAfter=4,
    )
    body_style = ParagraphStyle(
        'Body',
        parent=styles['BodyText'],
        fontName='Helvetica',
        fontSize=9,
        leading=13,
        textColor=charcoal,
    )
    bold_body_style = ParagraphStyle(
        'BoldBody',
        parent=body_style,
        fontName='Helvetica-Bold',
    )
    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#bf360c'),
    )

    # Header Banner
    story.append(Paragraph('AGROVISION AI', title_style))
    story.append(Paragraph('AI-Powered Crop Disease Intelligence & Smart Management Report', subtitle_style))
    story.append(Spacer(1, 0.1 * inch))
    story.append(HRFlowable(width='100%', thickness=1.5, color=primary_green, spaceAfter=8))

    # AI Screening Disclaimer Box
    disclaimer_text = (
        '<b>NOTICE:</b> This document is generated by an automated AI screening system for educational '
        'and preliminary assessment purposes. It does NOT constitute a certified plant pathology laboratory diagnosis. '
        'Always confirm disease identification and local agrochemical regulations with a licensed agricultural expert.'
    )
    disclaimer_table = Table([[Paragraph(disclaimer_text, disclaimer_style)]], colWidths=[7.5 * inch])
    disclaimer_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#fff3e0')),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#ffb74d')),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(disclaimer_table)
    story.append(Spacer(1, 0.15 * inch))

    # Primary Analysis Overview Table
    crop_name = safe_text(disease_data.get('crop'))
    disease_name = safe_text(disease_data.get('disease'))
    confidence_val = disease_data.get('confidence')
    confidence_str = f"{float(confidence_val):.2f}%" if confidence_val is not None else 'N/A'
    timestamp_val = safe_text(disease_data.get('timestamp'), datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC'))
    image_ref = safe_text(disease_data.get('image_filename'), 'leaf_image.jpg')

    overview_data = [
        [Paragraph('<b>Crop Evaluated:</b>', body_style), Paragraph(crop_name, bold_body_style),
         Paragraph('<b>Screening Result:</b>', body_style), Paragraph(disease_name, bold_body_style)],
        [Paragraph('<b>Confidence Score:</b>', body_style), Paragraph(confidence_str, bold_body_style),
         Paragraph('<b>Analysis Timestamp:</b>', body_style), Paragraph(timestamp_val, body_style)],
        [Paragraph('<b>Image Reference:</b>', body_style), Paragraph(image_ref, body_style),
         Paragraph('<b>Status:</b>', body_style), Paragraph(safe_text(disease_data.get('status'), 'Completed'), body_style)],
    ]
    overview_table = Table(overview_data, colWidths=[1.5 * inch, 2.25 * inch, 1.5 * inch, 2.25 * inch])
    overview_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), light_bg),
        ('GRID', (0, 0), (-1, -1), 0.5, border_color),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    story.append(overview_table)
    story.append(Spacer(1, 0.15 * inch))

    # Top Predictions Section
    top_preds = parse_top_predictions(disease_data.get('top_predictions'))
    if top_preds:
        story.append(Paragraph('Top Model Predictions', section_style))
        pred_table_data = [['Rank', 'Crop', 'Predicted Condition', 'Confidence (%)']]
        for rank, pred in enumerate(top_preds[:3], start=1):
            p_crop = safe_text(pred.get('crop'))
            p_dis = safe_text(pred.get('disease'))
            p_conf = pred.get('confidence_pct') or (pred.get('confidence') * 100 if pred.get('confidence') else 0.0)
            pred_table_data.append([str(rank), p_crop, p_dis, f"{float(p_conf):.2f}%"])

        pred_table = Table(pred_table_data, colWidths=[0.8 * inch, 1.8 * inch, 3.4 * inch, 1.5 * inch])
        pred_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), table_header_bg),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8.5),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ]))
        story.append(pred_table)
        story.append(Spacer(1, 0.1 * inch))

    # Disease Description
    story.append(Paragraph('Disease Description & Summary', section_style))
    summary_text = safe_text(disease_data.get('description') or disease_data.get('recommendation_summary'), 'No description available.')
    story.append(Paragraph(summary_text, body_style))
    story.append(Spacer(1, 0.08 * inch))

    # Symptoms and Causes
    symptoms = disease_data.get('symptoms', [])
    if symptoms:
        story.append(Paragraph('Observed Symptoms', section_style))
        for item in symptoms:
            story.append(Paragraph(f"• {safe_text(item)}", body_style))
        story.append(Spacer(1, 0.08 * inch))

    causes = disease_data.get('causes', [])
    if causes:
        story.append(Paragraph('Pathogen & Environmental Causes', section_style))
        for item in causes:
            story.append(Paragraph(f"• {safe_text(item)}", body_style))
        story.append(Spacer(1, 0.08 * inch))

    # Smart Management Recommendations
    story.append(Paragraph('Smart Agrochemical & Crop Management Guidance', section_style))

    # Chemical Management
    chemical_items = disease_data.get('chemical_management', [])
    story.append(Paragraph('<b>1. Chemical Management:</b>', body_style))
    if chemical_items:
        for chem in chemical_items:
            opt = safe_text(chem.get('option'), 'Option')
            reason = safe_text(chem.get('reason'), '')
            verified = chem.get('verified', False)
            source = safe_text(chem.get('source'), 'Not specified')
            tag = '<font color="#2e7d32"><b>[VERIFIED]</b></font>' if verified else '<font color="#d84315"><b>[UNVERIFIED - INFORMATIONAL / CONSULT EXTENSION]</b></font>'
            txt = f"• {tag} <b>{opt}</b><br/>&nbsp;&nbsp;&nbsp;&nbsp;{reason} (Source: {source})"
            story.append(Paragraph(txt, body_style))
    else:
        story.append(Paragraph('• No verified chemical options listed. Do not apply unverified pesticides.', body_style))
    story.append(Spacer(1, 0.06 * inch))

    # Biological Management
    bio_items = disease_data.get('biological_management', [])
    story.append(Paragraph('<b>2. Biological Management:</b>', body_style))
    if bio_items:
        for bio in bio_items:
            opt = safe_text(bio.get('option'), 'Biological option')
            reason = safe_text(bio.get('reason'), '')
            txt = f"• <b>{opt}</b>: {reason}" if reason else f"• <b>{opt}</b>"
            story.append(Paragraph(txt, body_style))
    else:
        story.append(Paragraph('• No specific biological control records listed in knowledge base for this condition.', body_style))
    story.append(Spacer(1, 0.06 * inch))

    # Cultural Management
    cultural_items = disease_data.get('cultural_management', [])
    story.append(Paragraph('<b>3. Cultural & Agronomic Management:</b>', body_style))
    if cultural_items:
        for cult in cultural_items:
            opt = safe_text(cult.get('option'), 'Cultural practice')
            reason = safe_text(cult.get('reason'), '')
            txt = f"• <b>{opt}</b>: {reason}" if reason else f"• <b>{opt}</b>"
            story.append(Paragraph(txt, body_style))
    else:
        story.append(Paragraph('• Maintain standard field sanitation, crop rotation, and healthy agronomic practices.', body_style))
    story.append(Spacer(1, 0.08 * inch))

    # Preventive Measures
    measures = disease_data.get('preventive_measures', [])
    if measures:
        story.append(Paragraph('Recommended Preventive Measures', section_style))
        for item in measures:
            story.append(Paragraph(f"• {safe_text(item)}", body_style))
        story.append(Spacer(1, 0.08 * inch))

    # Agricultural References Table
    references = disease_data.get('references', [])
    if references:
        story.append(Paragraph('Verified Agricultural References', section_style))
        ref_table_data = [['Source / Institution', 'Resource Link']]
        for ref in references:
            ref_name = safe_text(ref.get('name'), 'Agricultural Extension Source')
            ref_url = safe_text(ref.get('url'), 'N/A')
            ref_table_data.append([Paragraph(ref_name, body_style), Paragraph(ref_url, body_style)])

        ref_table = Table(ref_table_data, colWidths=[2.8 * inch, 4.7 * inch])
        ref_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), table_header_bg),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(ref_table)

    doc.build(story)
    return str(final_path)
